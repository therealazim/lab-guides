interface I18nContextType {
  lang: Lang
  setLang: (l: Lang) => void
  t: (key: string) => string
}

const I18nContext = createContext<I18nContextType>({
  lang: 'en',
  setLang: () => {},
  t: (k) => k,
})

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    if (typeof window === 'undefined') return 'en'
    const saved = localStorage.getItem('language') as Lang | null
    return saved && LANGUAGES.some(item => item.code === saved) ? saved : 'en'
  })

  useEffect(() => {
    document.documentElement.lang = lang
    localStorage.setItem('language', lang)
  }, [lang])
  const [overrides, _setOverrides] = useState<Record<string, Record<string, string>>>(() => {
    const initial = (window as any).__INITIAL_DATA__
    return initial?.translations || {}
  })
  const t = (key: string) => {
    const dbVal = overrides[key]?.[lang] || overrides[key]?.en
    if (dbVal) return dbVal
    return UI_STRINGS[lang]?.[key] ?? UI_STRINGS.en?.[key] ?? key
  }
  const setLangPersist = (l: Lang) => setLang(l)
  return (
    <I18nContext.Provider value={{ lang, setLang: setLangPersist, t }}>{children}</I18nContext.Provider>
  )
}

export function useI18n() {
  return useContext(I18nContext)
}
